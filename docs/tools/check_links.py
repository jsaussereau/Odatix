#!/usr/bin/env python3
"""Check the internal links of the built documentation site.

Hugo leaves a link to a page that does not exist as it is: the site builds and
the reader lands on a 404. This walks the HTML that `hugo` wrote and checks that
every internal link (href and src) points to a file of the site and, when it
names an anchor, that the target page has an element with that id.

External links are not fetched: the check must not depend on the network.

Usage: python docs/tools/check_links.py [public directory]
Exits with 1 and lists the broken links when there are any.
"""

import os
import sys
from html.parser import HTMLParser
from urllib.parse import unquote, urlsplit

# Generated by the theme on every page, not written by the documentation.
IGNORED_PREFIXES = ("/page/", "/tags/", "/categories/")


class PageParser(HTMLParser):
    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.links = []
        self.ids = set()
        self.redirect = None

    def handle_starttag(self, tag, attrs):
        attrs = dict(attrs)
        if attrs.get("id"):
            self.ids.add(attrs["id"])
        if tag == "a" and attrs.get("name"):
            self.ids.add(attrs["name"])
        for key in ("href", "src"):
            if attrs.get(key):
                self.links.append(attrs[key])
        # Hugo aliases are pages holding only a refresh to the real one.
        if tag == "meta" and (attrs.get("http-equiv") or "").lower() == "refresh":
            content = attrs.get("content") or ""
            if "url=" in content:
                self.redirect = content.split("url=", 1)[1].strip()


def parse(path):
    parser = PageParser()
    with open(path, encoding="utf-8", errors="replace") as f:
        parser.feed(f.read())
    return parser


def target_file(public, url_path):
    """The file of the site that serves url_path, or None."""
    local = os.path.join(public, unquote(url_path).lstrip("/"))
    if url_path.endswith("/") or os.path.isdir(local):
        local = os.path.join(local, "index.html")
    return local if os.path.isfile(local) else None


def is_internal(link):
    parts = urlsplit(link)
    if parts.scheme or parts.netloc or link.startswith(("mailto:", "javascript:", "data:")):
        return False
    return True


def check(public):
    pages = {}
    for root, _, files in os.walk(public):
        for name in files:
            if name.endswith(".html"):
                path = os.path.join(root, name)
                pages[path] = parse(path)

    def ids_of(path, seen=()):
        page = pages.get(path) or parse(path)
        if page.redirect and path not in seen:
            target = target_file(public, urlsplit(page.redirect).path)
            if target:
                return ids_of(target, seen + (path,))
        return page.ids

    broken = []
    for path, page in sorted(pages.items()):
        if page.redirect:
            continue
        page_url = "/" + os.path.relpath(os.path.dirname(path), public).replace(os.sep, "/") + "/"
        page_url = page_url.replace("/./", "/")
        for link in page.links:
            if not is_internal(link):
                continue
            parts = urlsplit(link)
            if parts.path:
                if parts.path.startswith("/"):
                    url_path = parts.path
                else:
                    url_path = os.path.normpath(os.path.join(page_url, parts.path))
                    if parts.path.endswith("/"):
                        url_path += "/"
                if url_path.startswith(IGNORED_PREFIXES):
                    continue
                target = target_file(public, url_path)
            else:
                target = path
            if target is None:
                broken.append((path, link, "no such page"))
            elif parts.fragment and target.endswith(".html") and unquote(parts.fragment) not in ids_of(target):
                broken.append((path, link, "no such anchor"))

    for path, link, reason in broken:
        print("{}: {} ({})".format(os.path.relpath(path, public), link, reason))
    print("{} pages checked, {} broken links".format(len(pages), len(broken)))
    return not broken


if __name__ == "__main__":
    public = sys.argv[1] if len(sys.argv) > 1 else "public"
    if not os.path.isdir(public):
        sys.exit("{} does not exist: build the site first (hugo -d {})".format(public, public))
    sys.exit(0 if check(public) else 1)
